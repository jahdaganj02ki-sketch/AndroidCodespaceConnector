val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun secretValue(name: String): String {
    val fromLocal = localProperties.getProperty(name)
    if (!fromLocal.isNullOrBlank()) return fromLocal
    val fromGradle = providers.gradleProperty(name).orNull
    if (!fromGradle.isNullOrBlank()) return fromGradle
    return System.getenv(name).orEmpty()
}

fun String.asBuildConfigValue(): String =
    replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "").replace("\r", "")

